#!/usr/bin/env node
/**
 * Parse docs/v2/content/*.md tables → mobile/www-src/local/habit-seed.js
 *
 * Canonical tables (content Agent):
 *   habit-templates.md, micro-steps.md, parent-scripts.md,
 *   celebration-copy.md, offline-celebration-hints.md, habit-board-copy.md
 * emotion-copy.md is retired (no longer seeded).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "../..");
const contentDir = path.join(root, "docs/v2/content");
const outJs = path.join(root, "mobile/www-src/local/habit-seed.js");

function parseMdTable(filePath) {
  if (!fs.existsSync(filePath)) return [];
  const text = fs.readFileSync(filePath, "utf8");
  const lines = text.split(/\r?\n/).filter((l) => l.trim().startsWith("|"));
  if (lines.length < 2) return [];
  const headers = lines[0]
    .split("|")
    .map((c) => c.trim())
    .filter(Boolean);
  const rows = [];
  for (let i = 2; i < lines.length; i++) {
    const cells = lines[i]
      .split("|")
      .map((c) => c.trim())
      .filter((_, idx, arr) => idx > 0 && idx < arr.length - 1);
    if (cells.length < headers.length) continue;
    if (cells.every((c) => /^[-:]+$/.test(c))) continue;
    const obj = {};
    headers.forEach((h, idx) => {
      obj[h] = cells[idx] ?? "";
    });
    rows.push(obj);
  }
  return rows;
}

function firstExisting(...names) {
  for (const name of names) {
    const p = path.join(contentDir, name);
    if (fs.existsSync(p)) return p;
  }
  return path.join(contentDir, names[0]);
}

const templates = parseMdTable(path.join(contentDir, "habit-templates.md")).map((r) => ({
  slug: r.slug,
  title: r.title,
  category: r.category,
  default_minutes: Number(r.default_minutes) || 5,
  active: r.active === "1" || r.active === "true",
  sort_default: Number(r.sort_default) || 100,
  notes: r.notes || "",
}));

const scripts = parseMdTable(path.join(contentDir, "parent-scripts.md")).map((r) => ({
  id: r.id,
  habit_slug: r.habit_slug || "",
  category: r.category || "",
  script_text: r.script_text,
  active: r.active !== "0",
}));

const hints = parseMdTable(path.join(contentDir, "offline-celebration-hints.md")).map((r) => ({
  id: r.id,
  title: r.title,
  body: r.body,
  image_key: r.image_key || "",
  categories: (r.categories || "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean),
  active: r.active !== "0",
}));

const microSteps = parseMdTable(
  firstExisting("micro-steps.md", "habit-micro-steps.md")
).map((r) => ({
  id: r.id,
  habit_slug: r.habit_slug || "",
  sort: Number(r.sort) || 100,
  step_text: r.step_text,
  active: r.active !== "0",
}));

const celebrationCopy = parseMdTable(path.join(contentDir, "celebration-copy.md")).map(
  (r) => ({
    id: r.id,
    habit_slug: r.habit_slug || "",
    category: r.category || "",
    incentive_text: r.incentive_text || "",
    small_celebration: r.small_celebration || "",
    offline_hint_id: r.offline_hint_id || "",
    active: r.active !== "0",
  })
);

const boardCopy = parseMdTable(path.join(contentDir, "habit-board-copy.md")).map((r) => ({
  id: r.id,
  slot: r.slot,
  copy_text: r.copy_text,
  active: r.active !== "0",
}));

const payload = {
  version: 3,
  generated_at: new Date().toISOString(),
  templates,
  scripts,
  hints,
  celebration_copy: celebrationCopy,
  micro_steps: microSteps,
  board_copy: boardCopy,
  // Retired: approach/avoid emotion-copy — kept empty for older readers
  emotions: [],
};

const js = `/* auto-generated by mobile/scripts/build-habit-content.mjs — do not edit */
(function (global) {
  "use strict";
  global.MyTimeTreeHabitSeed = ${JSON.stringify(payload, null, 2)};
})(typeof window !== "undefined" ? window : globalThis);
`;

fs.mkdirSync(path.dirname(outJs), { recursive: true });
fs.writeFileSync(outJs, js);
console.log(
  `[build-habit-content] templates=${templates.length} scripts=${scripts.length} hints=${hints.length} celebration_copy=${celebrationCopy.length} micro_steps=${microSteps.length} board_copy=${boardCopy.length} → ${path.relative(root, outJs)}`
);
